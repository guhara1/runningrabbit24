def build_nav(active):
    items = []
    for key, label, url, subs in NAV_ITEMS:
        cls = " is-active" if key == active else ""
        if subs:
            sub_html = "".join(
                f'<li><a href="{u}">{esc(t)}</a></li>' for t, u in subs)
            items.append(
                f'<li class="has-sub"><a class="{cls.strip()}" href="{url}">{esc(label)}</a>'
                f'<button class="sub-toggle" aria-label="{esc(label)} 하위메뉴" aria-expanded="false"></button>'
                f'<ul class="submenu">{sub_html}</ul></li>')
        else:
            items.append(f'<li><a class="{cls.strip()}" href="{url}">{esc(label)}</a></li>')
    return '<nav class="main-nav" aria-label="주요 메뉴"><ul>' + "".join(items) + "</ul></nav>"

